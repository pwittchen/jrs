//! A multi-module build into a workspace (`specs/WORKSPACES.md` §8): a
//! Maven aggregator's `<modules>`, or the projects `settings.gradle`
//! includes, each translated into a member manifest of its own, and a root
//! `jrs.toml` that lists them and holds what they all share.
//!
//! Each member is translated by the single-module readers as it always was,
//! with its parent chain (Maven) or the root's `subprojects { }` blocks and
//! version catalog (Gradle) in reach. What is the same in every member — the
//! `[java]` table, the repositories, the tail of `[managed]` the parent gave
//! them all — then moves up into the root, which the members inherit it
//! from; and a dependency on a sibling becomes a path to its directory.

use std::path::{Path, PathBuf};

use super::{Migration, Report, Source, gradle, maven};
use crate::error::{IoResultExt, JrsError, Result};
use crate::manifest::{self, MANIFEST_FILE, ModuleDependency};
use crate::resolve::pom::Pom;

/// One build, migrated into a workspace.
#[derive(Debug)]
pub struct WorkspaceMigration {
    pub source: Source,
    /// The root build file.
    pub source_file: PathBuf,
    /// The root's report: the members found, what moved into the root.
    pub report: Report,
    /// The root `jrs.toml`.
    pub root_manifest: String,
    /// Each member: its directory relative to the root (`.` for a root that
    /// is a member too), and its migration.
    pub members: Vec<(String, Migration)>,
}

impl WorkspaceMigration {
    /// How many members came through without a line to review or a thing
    /// left behind.
    #[must_use]
    pub fn clean(&self) -> usize {
        self.members
            .iter()
            .filter(|(_, m)| m.report.needs_review.is_empty() && m.report.not_migrated.is_empty())
            .count()
    }

    /// The header every file written gets.
    fn header(file: &Path) -> String {
        format!(
            "Generated by jrs {} from {}.\n\
             Review it before relying on it: translation is best-effort, and\n\
             the original build file was left untouched.",
            env!("CARGO_PKG_VERSION"),
            file.file_name().map_or_else(
                || file.display().to_string(),
                |n| n.to_string_lossy().into_owned()
            ),
        )
    }

    /// Every file the migration writes, relative to the root, with its text.
    #[must_use]
    pub fn files(&self) -> Vec<(String, String)> {
        let mut files = Vec::new();
        let root_member = self.members.iter().find(|(dir, _)| dir == ".");
        let root_text = if let Some((_, m)) = root_member {
            insert_workspace(
                &m.manifest.render(Some(&Self::header(&m.source_file))),
                &self.root_manifest,
            )
        } else {
            let mut text = String::new();
            for line in Self::header(&self.source_file).lines() {
                text.push_str("# ");
                text.push_str(line);
                text.push('\n');
            }
            text.push('\n');
            text.push_str(&self.root_manifest);
            text
        };
        files.push((MANIFEST_FILE.to_string(), root_text));
        for (dir, migration) in self.members.iter().filter(|(dir, _)| dir != ".") {
            files.push((
                format!("{dir}/{MANIFEST_FILE}"),
                migration
                    .manifest
                    .render(Some(&Self::header(&migration.source_file))),
            ));
        }
        files
    }
}

/// The `[workspace]` table and the shared tables, after a root member's
/// `[project]` table.
fn insert_workspace(member_text: &str, shared: &str) -> String {
    // The project table runs to the first blank line after it.
    let at = member_text.find("[project]").unwrap_or(0);
    let end = member_text[at..]
        .find("\n\n")
        .map_or(member_text.len(), |e| at + e + 1);
    let mut text = member_text[..end].to_string();
    text.push('\n');
    text.push_str(shared.trim_end());
    text.push('\n');
    text.push_str(&member_text[end..]);
    text
}

/// The workspace `dir` holds, when its build has modules: `None` for a
/// single-module build.
///
/// # Errors
///
/// As for [`maven::migrate`] and [`gradle::migrate`], for any member's
/// build file; [`JrsError::Usage`] when the build lists a module whose
/// directory has no build file.
pub fn plan(dir: &Path, source: Source, file: &Path) -> Result<Option<WorkspaceMigration>> {
    match source {
        Source::Maven => maven_workspace(dir, file),
        Source::Gradle => gradle_workspace(dir, file),
    }
}

// ---- Maven -----------------------------------------------------------------

fn maven_workspace(root: &Path, pom_path: &Path) -> Result<Option<WorkspaceMigration>> {
    let pom = read_pom(pom_path)?;
    if pom.modules.is_empty() && profile_modules(&pom).is_empty() {
        return Ok(None);
    }
    let mut report = Report::default();
    let mut found: Vec<(String, PathBuf)> = Vec::new();
    if pom.packaging != "pom" {
        found.push((".".to_string(), pom_path.to_path_buf()));
    }
    collect_modules(
        root,
        ".",
        &pom,
        (pom_path, pom_path),
        &mut found,
        &mut report,
    )?;

    let mut members = Vec::new();
    for (dir, path) in found {
        let member_root = if dir == "." {
            root.to_path_buf()
        } else {
            root.join(&dir)
        };
        let mut migration = maven::migrate(&path, &member_root)?;
        migration
            .report
            .not_migrated
            .retain(|line| !line.starts_with("<modules>"));
        members.push((dir, migration));
    }
    report.migrated(format!(
        "workspace.members = {} (from <modules>)",
        member_list(&members)
    ));
    link_maven_siblings(&mut members, &mut report);
    // The aggregator's own <dependencyManagement>, when it is the members'
    // parent: its versions go in the root's [managed] once.
    let managed: Vec<(String, String, String)> = crate::resolve::pom::effective(&[pom])
        .map(|effective| {
            effective
                .managed
                .iter()
                .filter(|(ga, _)| ga.classifier.is_none())
                .filter_map(|(ga, entry)| {
                    let version = entry.version.clone()?;
                    (!version.contains("${"))
                        .then(|| (ga.group.clone(), ga.artifact.clone(), version))
                })
                .collect()
        })
        .unwrap_or_default();
    Ok(Some(finish(
        Source::Maven,
        pom_path,
        root,
        members,
        report,
        (&managed, "the parent's <dependencyManagement>"),
    )))
}

/// Walk `pom`'s `<modules>`, recursively: a `jar` module is a member, an
/// aggregator's modules are walked in turn.
fn collect_modules(
    root: &Path,
    dir: &str,
    pom: &Pom,
    (pom_path, root_pom): (&Path, &Path),
    found: &mut Vec<(String, PathBuf)>,
    report: &mut Report,
) -> Result<()> {
    for (profile, modules) in profile_modules(pom) {
        report.review(format!(
            "<profile> {profile} — lists the modules {}, which a plain `mvn` build does not \
             build; they were left out of the workspace",
            modules.join(", ")
        ));
    }
    for module in &pom.modules {
        let child_dir = join_dir(dir, module);
        let child_root = root.join(&child_dir);
        let child_pom = if child_root.is_file() {
            child_root.clone()
        } else {
            child_root.join("pom.xml")
        };
        if !child_pom.is_file() {
            return Err(JrsError::usage(format!(
                "{} lists the module `{module}`, and {} does not exist",
                pom_path.display(),
                child_pom.display()
            )));
        }
        let child = read_pom(&child_pom)?;
        let child_dir = if child_root.is_file() {
            Path::new(&child_dir)
                .parent()
                .map_or_else(|| ".".to_string(), slash)
        } else {
            child_dir
        };
        // A parent that is not the root aggregator: the member reads it,
        // but the root's shared keys do not come from it.
        let parent_is_root = child.parent.as_ref().is_some_and(|p| {
            let relative = p.relative_path.as_deref().unwrap_or("../pom.xml");
            let mut parent = child_pom.parent().unwrap_or(root).join(relative);
            if parent.is_dir() {
                parent = parent.join("pom.xml");
            }
            same_file(&parent, root_pom)
        });
        if !parent_is_root && child.packaging != "pom" {
            report.review(format!(
                "{child_dir} — its <parent> is not the root POM; what that parent sets is in \
                 the member's own jrs.toml rather than shared through the root's"
            ));
        }
        if child.packaging == "pom" {
            if child.modules.is_empty() {
                report.skipped(format!(
                    "{child_dir} — a `pom`-packaged module with no modules of its own (a BOM \
                     or a parent), so not a member; a BOM it publishes goes in [managed]"
                ));
            } else {
                collect_modules(
                    root,
                    &child_dir,
                    &child,
                    (&child_pom, root_pom),
                    found,
                    report,
                )?;
            }
            continue;
        }
        if !found.iter().any(|(d, _)| *d == child_dir) {
            found.push((child_dir, child_pom));
        }
    }
    Ok(())
}

/// The modules each profile lists, by profile id.
fn profile_modules(pom: &Pom) -> Vec<(String, Vec<String>)> {
    pom.profiles
        .iter()
        .filter_map(|p| {
            let modules: Vec<String> = p
                .element
                .list("modules", "module")
                .into_iter()
                .map(|m| m.text.trim().to_string())
                .filter(|m| !pom.modules.contains(m))
                .collect();
            (!modules.is_empty()).then(|| (p.id.clone(), modules))
        })
        .collect()
}

/// A dependency on a sibling's own `groupId:artifactId` becomes a path to
/// its directory; the sibling's test jar has no counterpart.
fn link_maven_siblings(members: &mut [(String, Migration)], report: &mut Report) {
    let coordinates: Vec<(String, String, String, String)> = members
        .iter()
        .map(|(dir, m)| {
            (
                m.group.clone().unwrap_or_default(),
                m.manifest.name.clone(),
                dir.clone(),
                m.manifest.name.clone(),
            )
        })
        .collect();
    for (dir, migration) in members.iter_mut() {
        let out = &mut migration.manifest;
        for dev in [false, true] {
            let table = if dev {
                &mut out.dev_dependencies
            } else {
                &mut out.dependencies
            };
            let mut kept = Vec::new();
            let mut linked = Vec::new();
            for dep in table.drain(..) {
                let sibling = coordinates
                    .iter()
                    .find(|(g, a, d, _)| *g == dep.group && *a == dep.artifact && d != dir);
                match sibling {
                    Some((_, _, sibling_dir, name)) if dep.classifier.is_none() => {
                        linked.push(ModuleDependency {
                            name: name.clone(),
                            path: relative(dir, sibling_dir),
                            dev,
                            compile_only: dep.compile_only,
                            runtime_only: dep.runtime_only,
                        });
                    }
                    Some((_, _, _, name)) => {
                        migration.report.review(format!(
                            "{} — the `{}` jar of the member `{name}`, which jrs does not \
                             build; it was left out, and its classes may belong in a member \
                             of their own",
                            dep,
                            dep.classifier.as_deref().unwrap_or_default()
                        ));
                    }
                    None => kept.push(dep),
                }
            }
            *table = kept;
            for module in linked {
                let (group, artifact) = coordinates
                    .iter()
                    .find(|(_, _, _, name)| *name == module.name)
                    .map(|(g, a, _, _)| (g.clone(), a.clone()))
                    .unwrap_or_default();
                let written = format!("{group}:{artifact} (");
                migration
                    .report
                    .migrated
                    .retain(|line| !line.starts_with(&written));
                migration.report.migrated(format!(
                    "{} = {{ path = \"{}\" }} (a sibling module)",
                    module.name, module.path
                ));
                if !out.modules.iter().any(|m| m.name == module.name) {
                    out.modules.push(module);
                }
            }
        }
    }
    let links: usize = members.iter().map(|(_, m)| m.manifest.modules.len()).sum();
    if links > 0 {
        report.migrated(format!(
            "{links} dependencies on sibling modules became path dependencies"
        ));
    }
}

fn read_pom(path: &Path) -> Result<Pom> {
    let bytes = std::fs::read(path).path(path)?;
    Pom::parse(&bytes).map_err(|e| JrsError::usage(format!("{}: {e}", path.display())))
}

fn same_file(a: &Path, b: &Path) -> bool {
    match (a.canonicalize(), b.canonicalize()) {
        (Ok(a), Ok(b)) => a == b,
        _ => false,
    }
}

// ---- Gradle ----------------------------------------------------------------

fn gradle_workspace(root: &Path, build_file: &Path) -> Result<Option<WorkspaceMigration>> {
    let (paths, root_name) = gradle::settings_projects(root);
    if paths.is_empty() {
        return Ok(None);
    }
    let mut report = Report {
        preamble: Some(gradle::PREAMBLE.to_string()),
        ..Report::default()
    };
    let root_script = std::fs::read_to_string(build_file).path(build_file)?;
    let shared = gradle::shared_configuration(&root_script);
    if !shared.trim().is_empty() {
        report.migrated(
            "`subprojects { }` and `allprojects { }` — read into each member; what every \
             member ends up with moves into the root"
                .to_string(),
        );
    }

    let mut members = Vec::new();
    // The root project is a member when its own script builds sources.
    if root.join("src").is_dir() {
        let mut migration = gradle::migrate_with(
            build_file,
            root,
            Some(&gradle::Subproject {
                settings_root: root,
                name: root_name.clone().unwrap_or_else(|| dir_name(root)),
                shared: String::new(),
            }),
        )?;
        migration
            .report
            .not_migrated
            .retain(|l| !l.starts_with("settings.gradle includes"));
        members.push((".".to_string(), migration));
    }
    for path in &paths {
        let dir = path.trim_start_matches(':').replace(':', "/");
        let member_root = root.join(&dir);
        let file = ["build.gradle.kts", "build.gradle"]
            .iter()
            .map(|f| member_root.join(f))
            .find(|f| f.is_file());
        let Some(file) = file else {
            report.review(format!(
                "{path} — no build.gradle(.kts) in {}; a project whose `projectDir` \
                 settings.gradle moves elsewhere is not followed, so it is not a member",
                member_root.display()
            ));
            continue;
        };
        let name = dir.rsplit('/').next().unwrap_or(&dir).to_string();
        let migration = gradle::migrate_with(
            &file,
            &member_root,
            Some(&gradle::Subproject {
                settings_root: root,
                name,
                shared: shared.clone(),
            }),
        )?;
        members.push((dir, migration));
    }
    if members.is_empty() {
        return Ok(None);
    }
    report.migrated(format!(
        "workspace.members = {} (from settings.gradle)",
        member_list(&members)
    ));
    link_gradle_projects(&mut members, &mut report);
    let catalog = gradle::catalog_versions(root);
    Ok(Some(finish(
        Source::Gradle,
        build_file,
        root,
        members,
        report,
        (&catalog, "the version catalog"),
    )))
}

/// `project(":core")` and `projects.core` become paths to the member's
/// directory, named by its project name.
fn link_gradle_projects(members: &mut [(String, Migration)], report: &mut Report) {
    let known: Vec<(String, String)> = members
        .iter()
        .map(|(dir, m)| (dir.clone(), m.manifest.name.clone()))
        .collect();
    let squash = |s: &str| {
        s.chars()
            .filter(|c| c.is_alphanumeric())
            .flat_map(char::to_lowercase)
            .collect::<String>()
    };
    let mut links = 0;
    for (dir, migration) in members.iter_mut() {
        let modules = std::mem::take(&mut migration.manifest.modules);
        for mut module in modules {
            let target = if let Some(accessor) = module.path.strip_prefix("projects.") {
                let wanted: Vec<String> = accessor.split('.').map(&squash).collect();
                known.iter().find(|(d, _)| {
                    let parts: Vec<String> = d.split('/').map(&squash).collect();
                    parts == wanted
                })
            } else {
                let wanted = module.path.trim_start_matches(':').replace(':', "/");
                known.iter().find(|(d, _)| *d == wanted)
            };
            let Some((target_dir, name)) = target else {
                migration.report.skipped(format!(
                    "a dependency on the project `{}`, which is not a member of the workspace",
                    module.path
                ));
                continue;
            };
            if target_dir == dir {
                continue;
            }
            module.name.clone_from(name);
            module.path = relative(dir, target_dir);
            migration.report.migrated(format!(
                "{} = {{ path = \"{}\" }} (from project(\":{}\"))",
                module.name,
                module.path,
                target_dir.replace('/', ":")
            ));
            if !migration
                .manifest
                .modules
                .iter()
                .any(|m| m.name == module.name)
            {
                migration.manifest.modules.push(module);
                links += 1;
            }
        }
    }
    if links > 0 {
        report.migrated(format!(
            "{links} project(...) dependencies became path dependencies"
        ));
    }
}

fn dir_name(root: &Path) -> String {
    root.canonicalize()
        .ok()
        .and_then(|p| p.file_name().map(|n| n.to_string_lossy().into_owned()))
        .unwrap_or_else(|| "app".to_string())
}

// ---- the root --------------------------------------------------------------

/// Move what every member shares into the root, and write the root's text.
fn finish(
    source: Source,
    source_file: &Path,
    root: &Path,
    mut members: Vec<(String, Migration)>,
    mut report: Report,
    (versions, from): (&[(String, String, String)], &str),
) -> WorkspaceMigration {
    let mut shared = manifest::blank("workspace", "0", root);

    // [java], when every member's is the same.
    let first_java = members[0].1.manifest.java.clone();
    if first_java != manifest::JavaConfig::default()
        && members.iter().all(|(_, m)| m.manifest.java == first_java)
    {
        shared.java = first_java;
        for (_, m) in &mut members {
            m.manifest.java = manifest::JavaConfig::default();
        }
        report.migrated("[java] — the same in every member, so set once in the root");
    }

    // [repositories], when every member's are the same.
    let first_repositories = members[0].1.manifest.repositories.clone();
    if first_repositories.len() > 1
        && members
            .iter()
            .all(|(_, m)| m.manifest.repositories == first_repositories)
    {
        shared.repositories = first_repositories;
        for (_, m) in &mut members {
            m.manifest.repositories = manifest::blank("x", "0", root).repositories;
        }
        report.migrated("[repositories] — the same in every member, so set once in the root");
    }

    hoist_versions(&mut members, &mut shared, versions, from, &mut report);
    hoist_managed_tail(&mut members, &mut shared, &mut report);

    let mut workspace = String::from("[workspace]\nmembers = [");
    let listed: Vec<String> = members
        .iter()
        .filter(|(dir, _)| dir != ".")
        .map(|(dir, _)| format!("\"{dir}\""))
        .collect();
    workspace.push_str(&listed.join(", "));
    workspace.push_str("]\n");
    // The shared tables, as a manifest renders them, without its [project].
    let rendered = shared.render(None);
    let tables = rendered.find("\n[").map_or("", |at| &rendered[at..]);
    workspace.push_str(tables);

    let clean = members
        .iter()
        .filter(|(_, m)| m.report.needs_review.is_empty() && m.report.not_migrated.is_empty())
        .count();
    report.migrated(format!(
        "{} members, {clean} of them without anything to review",
        members.len()
    ));
    WorkspaceMigration {
        source,
        source_file: source_file.to_path_buf(),
        report,
        root_manifest: workspace,
        members,
    }
}

/// The version catalog, or the parent's `<dependencyManagement>`: what the
/// members use of it is versioned once, in the root's `[managed]`, and the
/// members' declarations take their versions from there.
fn hoist_versions(
    members: &mut [(String, Migration)],
    shared: &mut manifest::Manifest,
    versions: &[(String, String, String)],
    from: &str,
    report: &mut Report,
) {
    for (group, artifact, version) in versions {
        let used = members.iter().any(|(_, m)| {
            m.manifest
                .dependencies
                .iter()
                .chain(&m.manifest.dev_dependencies)
                .any(|d| d.group == *group && d.artifact == *artifact && d.version == *version)
        });
        if !used {
            continue;
        }
        shared
            .managed
            .push(manifest::Managed::new(group, artifact, version));
        for (_, m) in members.iter_mut() {
            let manifest = &mut m.manifest;
            for d in manifest
                .dependencies
                .iter_mut()
                .chain(manifest.dev_dependencies.iter_mut())
            {
                if d.group == *group && d.artifact == *artifact && d.version == *version {
                    d.version.clear();
                }
            }
        }
    }
    if !shared.managed.is_empty() {
        report.migrated(format!(
            "[managed] — {} versions from {from}, set once in the root",
            shared.managed.len()
        ));
        // What a member pinned itself at the version the root now holds,
        // it inherits.
        for (_, m) in members.iter_mut() {
            m.manifest
                .managed
                .retain(|entry| entry.bom || !shared.managed.contains(entry));
        }
    }
}

/// The tail of `[managed]` every member ends with: what their parent's
/// `<dependencyManagement>` gave them all. Inherited entries come after a
/// member's own, so only a common tail keeps each member's order.
fn hoist_managed_tail(
    members: &mut [(String, Migration)],
    shared: &mut manifest::Manifest,
    report: &mut Report,
) {
    let lists: Vec<&Vec<manifest::Managed>> =
        members.iter().map(|(_, m)| &m.manifest.managed).collect();
    let shortest = lists.iter().map(|l| l.len()).min().unwrap_or(0);
    let mut tail = 0;
    while tail < shortest {
        let at = |l: &Vec<manifest::Managed>| l[l.len() - 1 - tail].clone();
        let candidate = at(lists[0]);
        if lists.iter().all(|l| at(l) == candidate) {
            tail += 1;
        } else {
            break;
        }
    }
    if tail > 0 {
        let list = &members[0].1.manifest.managed;
        let common: Vec<manifest::Managed> = list[list.len() - tail..].to_vec();
        for entry in common {
            if !shared.managed.iter().any(|m| m.key() == entry.key()) {
                shared.managed.push(entry);
            }
        }
        for (_, m) in members.iter_mut() {
            let keep = m.manifest.managed.len() - tail;
            m.manifest.managed.truncate(keep);
        }
        report.migrated(format!(
            "[managed] — {tail} entries every member shares, set once in the root"
        ));
    }
}

fn member_list(members: &[(String, Migration)]) -> String {
    members
        .iter()
        .map(|(dir, m)| {
            if dir == "." {
                format!("{} (the root)", m.manifest.name)
            } else {
                dir.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Write every file, refusing to overwrite a `jrs.toml` without `force`.
/// Returns the paths written.
///
/// # Errors
///
/// [`JrsError::Usage`] when a `jrs.toml` exists and `force` is not set, and
/// [`JrsError::Io`] when one cannot be written.
pub fn write(migration: &WorkspaceMigration, root: &Path, force: bool) -> Result<Vec<PathBuf>> {
    let files = migration.files();
    if !force && let Some((existing, _)) = files.iter().find(|(f, _)| root.join(f).exists()) {
        return Err(JrsError::usage(format!(
            "{} already exists\n\npass --force to overwrite it, or --dry-run to see what \
             would be written",
            root.join(existing).display()
        )));
    }
    let mut written = Vec::new();
    for (file, text) in files {
        let path = root.join(&file);
        std::fs::write(&path, text).path(&path)?;
        written.push(path);
    }
    Ok(written)
}

/// `to` relative to `from`, both directories relative to the root.
fn relative(from: &str, to: &str) -> String {
    let ups = if from == "." {
        0
    } else {
        from.split('/').count()
    };
    let mut parts: Vec<&str> = std::iter::repeat_n("..", ups).collect();
    if to != "." {
        parts.extend(to.split('/'));
    }
    if parts.is_empty() {
        ".".to_string()
    } else {
        parts.join("/")
    }
}

fn join_dir(dir: &str, module: &str) -> String {
    let module = module.trim().trim_end_matches('/').replace('\\', "/");
    if dir == "." {
        module
    } else {
        format!("{dir}/{module}")
    }
}

fn slash(p: &Path) -> String {
    let s = p
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("/");
    if s.is_empty() { ".".to_string() } else { s }
}

