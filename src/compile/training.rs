//! The generated part of the workload jrs trains `javac`'s AOT cache on
//! (`specs/todo/BEATING_THE_DAEMON_4.md` §5).
//!
//! `Training.java` makes most of the compiler run, but once: a cache trained
//! on it knows which classes `javac` loads, not which of its methods are hot
//! in a compile of a few thousand sources. Those method profiles (JDK 25,
//! JEP 515) are what a large compile spends its first second without, its
//! JIT warming up, so the training compiles a project's worth of classes as
//! well, in the training of `javac`'s own cache: [`CLASSES`] of them in packages of [`PER_PACKAGE`], each calling into
//! the classes before it, in four shapes that take turns — a class with
//! generic methods and streams, a record, an enum with constant bodies, and
//! nested types with lambdas, an anonymous class and checked exceptions.
//!
//! The `javac` worker's cache is not trained on them, nor is a worker
//! primed with them: on the worker they bought `gen-2000`'s `abi` 23 ms for
//! 0.24–0.31 s of `cold`, and a prime has to be done by the time the second
//! member is ready.
//!
//! Nothing here is a project's, and nothing of it is ever run or kept. The
//! sources are the same on every machine and in every command, so two
//! trainings compile the same thing.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// How many classes the generated workload holds: 300 make `gen-2000`'s
/// whole-unit `javac` 165 ms faster than the hand-written workload alone,
/// of the 217 ms a cache trained on `gen-2000` itself makes it; 150 make it
/// 120 ms faster, 600 make it 185 ms, each recording longer (1.2, 1.6 and
/// 2.0 s on an M4 Max).
pub(crate) const CLASSES: usize = 300;

/// Classes per package, as a project of this size might have.
const PER_PACKAGE: usize = 20;

/// Write [`CLASSES`] generated sources under `dir`, in a directory per
/// package, and return them.
pub(crate) fn write(dir: &Path) -> Option<Vec<PathBuf>> {
    write_classes(dir, CLASSES)
}

fn write_classes(dir: &Path, classes: usize) -> Option<Vec<PathBuf>> {
    let mut written = Vec::with_capacity(classes);
    let mut rng = 0x6A72_7374_7261_696E_u64;
    for k in 0..classes {
        let package = package_of(k);
        let first = k - k % PER_PACKAGE;
        let mut calls = Vec::new();
        if k == first {
            if k > 0 {
                calls.push(0);
                calls.push(k - PER_PACKAGE);
            }
        } else {
            calls.push(first);
            for _ in 0..2 {
                rng = rng
                    .wrapping_mul(6_364_136_223_846_793_005)
                    .wrapping_add(1_442_695_040_888_963_407);
                let span = (k - first) as u64;
                let j = first + usize::try_from((rng >> 33) % span).unwrap_or(0);
                if !calls.contains(&j) {
                    calls.push(j);
                }
            }
        }
        let package_dir = dir.join(package.replace('.', "/"));
        std::fs::create_dir_all(&package_dir).ok()?;
        let path = package_dir.join(format!("{}.java", class_name(k)));
        std::fs::write(&path, source(k, &calls)).ok()?;
        written.push(path);
    }
    Some(written)
}

fn package_of(k: usize) -> String {
    format!("train.p{:02}", k / PER_PACKAGE)
}

fn class_name(k: usize) -> String {
    format!("C{k:04}")
}

/// The source of class `k`, whose `value` calls the classes in `calls`.
fn source(k: usize, calls: &[usize]) -> String {
    let package = package_of(k);
    let class = class_name(k);
    let mut body = String::new();
    for &j in calls {
        let _ = writeln!(
            body,
            "        v += {}.{}.value(x - 1);",
            package_of(j),
            class_name(j)
        );
    }
    let value = format!(
        "    public static int value(int x) {{
        if (x <= 0) {{
            return {k};
        }}
        int v = x * 31 + {k};
{body}        return v;
    }}
"
    );
    let shape = match k % 4 {
        0 => service(&class, &value),
        1 => record(&class, &value),
        2 => enumeration(&class, &value),
        _ => nested(&class, &value),
    };
    format!(
        "package {package};

import java.io.IOException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.TreeMap;
import java.util.function.Function;
import java.util.stream.Collectors;

/** Generated by jrs for its compiler's training; never run. */
{shape}"
    )
}

fn service(class: &str, value: &str) -> String {
    format!(
        "public final class {class} {{
    private final Map<String, List<Integer>> index = new TreeMap<>();

{value}
    public List<String> names(List<? extends CharSequence> items) {{
        return items.stream()
                .map(CharSequence::toString)
                .filter(s -> !s.isEmpty())
                .sorted(Comparator.reverseOrder())
                .collect(Collectors.toList());
    }}

    public static <T extends Comparable<? super T>> T largest(List<T> items, T fallback) {{
        T best = fallback;
        for (T item : items) {{
            if (best == null || item.compareTo(best) > 0) {{
                best = item;
            }}
        }}
        return best;
    }}

    public void add(String key, int value) {{
        index.computeIfAbsent(key, k -> new ArrayList<>()).add(value);
    }}

    public Map<Integer, Long> histogram() {{
        return index.values().stream()
                .flatMap(List::stream)
                .collect(Collectors.groupingBy(Function.identity(), TreeMap::new, Collectors.counting()));
    }}

    @Override
    public String toString() {{
        return \"{class}\" + index + \" of \" + index.size();
    }}
}}
"
    )
}

fn record(class: &str, value: &str) -> String {
    format!(
        "public record {class}(String name, int count, List<String> tags) implements Comparable<{class}> {{
    public {class} {{
        Objects.requireNonNull(name, \"name\");
        tags = List.copyOf(tags);
    }}

{value}
    public {class} withCount(int n) {{
        return new {class}(name, n, tags);
    }}

    @Override
    public int compareTo({class} other) {{
        return Comparator.comparing({class}::name)
                .thenComparingInt({class}::count)
                .compare(this, other);
    }}

    public String describe() {{
        return switch (count % 3) {{
            case 0 -> \"none\";
            case 1 -> name + \":\" + count;
            default -> {{
                String joined = String.join(\",\", tags);
                yield joined.isEmpty() ? name : joined;
            }}
        }};
    }}
}}
"
    )
}

fn enumeration(class: &str, value: &str) -> String {
    format!(
        "public enum {class} {{
    LOW(1),
    MID(2) {{
        @Override
        int scale(int x) {{
            return x * weight;
        }}
    }},
    HIGH(3);

    final int weight;

    {class}(int weight) {{
        this.weight = weight;
    }}

    int scale(int x) {{
        return x + weight;
    }}

{value}
    public static Optional<{class}> parse(String text) {{
        return Arrays.stream(values())
                .filter(v -> v.name().equalsIgnoreCase(text))
                .findFirst();
    }}

    public String label() {{
        return switch (this) {{
            case LOW -> \"low\";
            case MID -> \"mid\";
            case HIGH -> \"high\";
        }};
    }}
}}
"
    )
}

fn nested(class: &str, value: &str) -> String {
    format!(
        "public final class {class} {{
    private {class}() {{}}

    public interface Handler<T> {{
        T handle(String input) throws IOException;

        default Handler<T> or(Handler<T> other) {{
            return input -> {{
                try {{
                    return handle(input);
                }} catch (IOException e) {{
                    return other.handle(input);
                }}
            }};
        }}
    }}

    abstract static class Base implements Handler<Integer> {{
        protected final String prefix;

        Base(String prefix) {{
            this.prefix = prefix;
        }}
    }}

    static final class Length extends Base {{
        Length() {{
            super(\"length\");
        }}

        @Override
        public Integer handle(String input) throws IOException {{
            if (input.isEmpty()) {{
                throw new IOException(prefix + \": empty\");
            }}
            return input.length();
        }}
    }}

{value}
    public static String run(String... inputs) {{
        StringBuilder out = new StringBuilder();
        Handler<Integer> handler = new Length().or(String::hashCode);
        for (String input : inputs) {{
            try {{
                out.append(handler.handle(input));
            }} catch (IOException e) {{
                out.append(e.getMessage());
            }} finally {{
                out.append(';');
            }}
        }}
        Object length = inputs.length;
        if (length instanceof Integer n && n > 2) {{
            out.append(\"many\");
        }}
        return out.toString();
    }}

    public static Runnable counter(int[] box) {{
        return new Runnable() {{
            @Override
            public void run() {{
                box[0]++;
            }}
        }};
    }}
}}
"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_classes_call_only_the_ones_before_them_and_are_the_same_every_time() {
        let root = std::env::temp_dir().join(format!("jrs-training-{}", std::process::id()));
        let first = write_classes(&root.join("a"), 45).unwrap();
        let second = write_classes(&root.join("b"), 45).unwrap();
        assert_eq!(first.len(), 45);
        for (a, b) in first.iter().zip(&second) {
            assert_eq!(std::fs::read(a).unwrap(), std::fs::read(b).unwrap());
        }
        let last = std::fs::read_to_string(&first[44]).unwrap();
        assert!(last.starts_with("package train.p02;"), "{last}");
        assert!(last.contains("train.p02.C0040.value(x - 1)"), "{last}");
        let _ = std::fs::remove_dir_all(&root);
    }
}
